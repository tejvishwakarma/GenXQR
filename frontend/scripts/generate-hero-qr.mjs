/**
 * Generates src/components/marketing/heroQrMatrix.ts — the module matrix for
 * the REAL, scannable QR code drawn in the homepage hero (QrArt).
 *
 * It used to be a decorative pattern that did not scan, on the homepage of a QR
 * company where visitors will try. It now opens the free generator, tagged
 * utm_source=hero_qr so those visits show up in sign-up attribution
 * (frontend/src/lib/attribution.ts).
 *
 * Error correction H: QrArt covers the centre with the GenXQR mark, and H can
 * recover ~30% of codewords. The URL fits version 6 (41×41), which has no
 * centre alignment pattern for the mark to hide.
 *
 * Run from frontend/: node scripts/generate-hero-qr.mjs
 * Uses the backend's `qrcode` dependency (the frontend does not ship it).
 */
import fs from "node:fs"
import path from "node:path"
import { createRequire } from "node:module"
import { fileURLToPath } from "node:url"

const HERO_QR_URL = "https://genxqr.com/generate?utm_source=hero_qr"

const here = path.dirname(fileURLToPath(import.meta.url))
const requireFromBackend = createRequire(path.resolve(here, "../../backend/package.json"))
const QRCode = requireFromBackend("qrcode")

const qr = QRCode.create(HERO_QR_URL, { errorCorrectionLevel: "H" })
const size = qr.modules.size
const rows = []
for (let y = 0; y < size; y++) {
  let row = ""
  for (let x = 0; x < size; x++) row += qr.modules.get(y, x) ? "1" : "0"
  rows.push(row)
}

const out = `// GENERATED by scripts/generate-hero-qr.mjs — do not edit by hand.
// Version ${qr.version}, error correction H, ${size}×${size} modules.
export const HERO_QR_URL = ${JSON.stringify(HERO_QR_URL)}
export const HERO_QR_ROWS: readonly string[] = ${JSON.stringify(rows, null, 2)}
`
const target = path.resolve(here, "../src/components/marketing/heroQrMatrix.ts")
fs.writeFileSync(target, out)
console.log(`hero QR: version ${qr.version}, ${size}×${size} → ${path.relative(process.cwd(), target)}`)
