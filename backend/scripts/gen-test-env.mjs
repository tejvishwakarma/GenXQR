/**
 * Generates backend/.env.test, the environment the Vitest suite runs against.
 *
 * Three sources, in priority order:
 *   1. TEST_DATABASE_URL / TEST_REDIS_URL from the environment — used by CI,
 *      where there is no local .env and the service containers supply their
 *      own credentials.
 *   2. The local .env, with the database name swapped to genxqr_test.
 *   3. DATABASE_URL / REDIS_URL already present in the environment, likewise
 *      with the database name swapped. This is the production case: on the
 *      server there is no backend/.env because secrets live in an env file
 *      outside the repo, which deploy.sh sources before calling this.
 *
 * However it is resolved, the result must point at genxqr_test; the suite
 * truncates tables, so pointing it anywhere else would destroy real data. The
 * name swap plus the assertion below are what make deriving from a PRODUCTION
 * url safe — if the swap ever fails to apply, this refuses to write the file
 * rather than handing the suite a live database.
 */
import fs from "node:fs"

const TEST_DB_NAME = "genxqr_test"

function fromLocalEnvFile() {
  if (!fs.existsSync(".env")) return null

  const text = fs.readFileSync(".env", "utf8")
  const read = (key) => text.match(new RegExp(`^${key}="?([^"\n]*)"?`, "m"))?.[1] ?? ""

  const dbUrl = read("DATABASE_URL")
  const redisUrl = read("REDIS_URL")
  if (!dbUrl || !redisUrl) return null

  return {
    // Swap only the database segment, preserving host/port/credentials/params.
    dbUrl: dbUrl.replace(/\/[^/?]+(\?|$)/, `/${TEST_DB_NAME}$1`),
    redisUrl,
    source: ".env",
  }
}

function fromEnvironment() {
  const dbUrl = process.env.TEST_DATABASE_URL
  const redisUrl = process.env.TEST_REDIS_URL
  if (!dbUrl || !redisUrl) return null
  return { dbUrl, redisUrl, source: "TEST_DATABASE_URL / TEST_REDIS_URL" }
}

/**
 * Derives the test settings from a live DATABASE_URL / REDIS_URL in the
 * environment, swapping the database name. Used on the production server, where
 * secrets sit in an env file outside the repo rather than in backend/.env.
 */
function fromLiveEnvironment() {
  const dbUrl = process.env.DATABASE_URL
  const redisUrl = process.env.REDIS_URL
  if (!dbUrl || !redisUrl) return null

  return {
    // Swap only the database segment, preserving host/port/credentials/params.
    // The assertion below is the real safeguard: if this substitution does not
    // land, the script aborts rather than targeting the live database.
    dbUrl: dbUrl.replace(/\/[^/?]+(\?|$)/, `/${TEST_DB_NAME}$1`),
    redisUrl,
    source: "DATABASE_URL / REDIS_URL (database name swapped)",
  }
}

const resolved = fromEnvironment() ?? fromLocalEnvFile() ?? fromLiveEnvironment()

if (!resolved) {
  console.error(
    "Could not determine test database settings.\n" +
      "Provide TEST_DATABASE_URL and TEST_REDIS_URL, create backend/.env, or run\n" +
      "with DATABASE_URL and REDIS_URL in the environment. On the server:\n" +
      "  set -a && source /home/genxqr/genxqr.env && set +a && pnpm test:setup",
  )
  process.exit(1)
}

if (!new RegExp(`/${TEST_DB_NAME}(\\?|$)`).test(resolved.dbUrl)) {
  console.error(
    `REFUSING: the test DATABASE_URL must target the "${TEST_DB_NAME}" database ` +
      `(the suite truncates tables). Got: ${resolved.dbUrl.replace(/:[^:@]+@/, ":****@")}`,
  )
  process.exit(1)
}

// Redis logical DB 15 is reserved for tests so flushing it can never clear dev
// rate-limit counters or queued jobs. Only append if one isn't already set.
let redisUrl = /\/\d+$/.test(resolved.redisUrl) ? resolved.redisUrl : `${resolved.redisUrl}/15`

/**
 * Pin "localhost" to 127.0.0.1. docker-compose binds the dev containers to
 * 127.0.0.1 only (deliberately — they must not be reachable off-box), which
 * means IPv4 exclusively. Node 18+ resolves "localhost" to ::1 first, so the
 * connection is refused before it ever tries IPv4. Rewriting the host avoids
 * a multi-second retry storm followed by a hard failure.
 */
function pinToIPv4(url) {
  return url.replace("://localhost:", "://127.0.0.1:").replace("@localhost:", "@127.0.0.1:")
}

redisUrl = pinToIPv4(redisUrl)
resolved.dbUrl = pinToIPv4(resolved.dbUrl)

const contents = `# Test environment — used by vitest only (see vitest.config.ts).
# GENERATED by scripts/gen-test-env.mjs — edit that script, not this file.
#
# Points at the SEPARATE ${TEST_DB_NAME} database so tests can truncate freely
# without ever touching dev data. Redis logical DB 15 is likewise reserved for
# tests. Gitignored, since it inherits real local credentials.
NODE_ENV=test
PORT=3099
DATABASE_URL="${resolved.dbUrl}"
REDIS_URL="${redisUrl}"
JWT_ACCESS_SECRET="test_only_access_secret_not_used_anywhere_real_0000000000000000"
JWT_REFRESH_SECRET="test_only_refresh_secret_not_used_anywhere_real_000000000000000"
JWT_ACCESS_EXPIRES_IN="15m"
JWT_REFRESH_EXPIRES_IN="30d"
FRONTEND_URL="http://localhost:5173"
# HTTPS on purpose: Cashfree requires notify_url to be HTTPS, and the tests
# assert the webhook is registered on each order. No server listens here.
BACKEND_URL="https://test.genxqr.local"
EMAIL_FROM="GenXQR Test <test@example.com>"
CASHFREE_APP_ID="test_app_id"
CASHFREE_SECRET_KEY="test_secret_key"
CASHFREE_API_BASE="https://sandbox.cashfree.com/pg"
`

fs.writeFileSync(".env.test", contents)
console.log(`Wrote backend/.env.test (from ${resolved.source})`)
console.log(contents.replace(/(:)[^:@"/]+(@)/g, "$1****$2"))
